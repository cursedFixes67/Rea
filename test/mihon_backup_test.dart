import 'dart:convert';
import 'dart:typed_data';

import 'package:archive/archive.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:dream_reader/data/mihon_backup.dart';
import 'package:dream_reader/domain/models.dart';

List<int> varint(int value) {
  final out = <int>[];
  do {
    out.add((value & 127) | (value > 127 ? 128 : 0));
    value >>= 7;
  } while (value != 0);
  return out;
}

List<int> text(int field, String value) => blob(field, utf8.encode(value));
List<int> blob(int field, List<int> bytes) => [
  ...varint(field << 3 | 2),
  ...varint(bytes.length),
  ...bytes,
];
List<int> number(int field, int value) => [
  ...varint(field << 3),
  ...varint(value),
];
void main() {
  test(
    'imports current Mihon protobuf fields, packed categories and chapter memo',
    () {
      // Field numbers independently pinned to upstream Backup*.kt, not generated by the importer.
      final float = ByteData(4)..setFloat32(0, 12.5, Endian.little);
      final chapter = [
        ...text(1, '/chapter'),
        ...text(2, 'Chapter 12.5'),
        ...number(4, 1),
        ...number(5, 1),
        ...number(6, 7),
        ...varint(9 << 3 | 5),
        ...float.buffer.asUint8List(),
        ...text(13, '{"pageKey":"abc"}'),
      ];
      final manga = [
        ...number(1, 123456789),
        ...text(2, '/story'),
        ...text(3, 'A story'),
        ...text(4, 'Artist'),
        ...blob(16, chapter),
        ...blob(17, varint(5)),
        ...number(111, 1),
        ...text(112, '{"edition":2}'),
      ];
      final category = [...text(1, 'Favorites'), ...number(3, 5)];
      final bytes = Uint8List.fromList(
        GZipEncoder().encode([...blob(1, manga), ...blob(2, category)]),
      );
      final imported = MihonBackupImporter.decode(bytes);
      final library = (imported['library'] as List).single;
      expect(library['category'], 'Favorites');
      final title = Manga.fromJson(jsonDecode(library['payload']));
      expect(title.sourceId, '123456789');
      expect(title.memo, {'edition': 2});
      final row = (imported['chapters'] as List).single;
      final decoded = Chapter.fromJson(jsonDecode(row['payload']));
      expect(decoded.number, 12.5);
      expect(decoded.memo, {'pageKey': 'abc'});
      expect(row['completed'], isTrue);
      expect(row['page'], 7);
      expect(
        jsonDecode(
          imported['settings']['bookmarks'],
        )['123456789::/story::/chapter'],
        7,
      );
      expect(imported['repositories'], isEmpty);
    },
  );
  test('rejects a gzip file without a compatible library', () {
    expect(
      () => MihonBackupImporter.decode(
        Uint8List.fromList(GZipEncoder().encode([8, 0])),
      ),
      throwsA(isA<Exception>()),
    );
  });
}
